def dibujar(img, x, y, txt, col, hueco=1, espacio=6):
    """Escribe `txt` con la letra gótica desde (x, y); ' ' deja `espacio` px. Devuelve la x final."""
    for c in txt:
        if c == ' ':
            x += espacio
            continue
        g = G[c]
        for dy, fila in enumerate(g):
            for dx, v in enumerate(fila):
                if v == '#':
                    img[y + dy][(x + dx) % len(img[0])] = col
        x += len(g[0]) + hueco
    return x


def ancho(txt, hueco=1, espacio=6):
    return sum(espacio if c == ' ' else len(G[c][0]) + hueco for c in txt)
