CTRL={0xFA:'\l',0xFB:'\p',0xFE:'\n'}
def decode(b,i,maxlen=2000):
    out=[];j=i
    while j<len(b) and j-i<maxlen:
        c=b[j]
        if c==0xFF: return ''.join(out),j+1
        if c in T: out.append(T[c]); j+=1
        elif c in CTRL: out.append(CTRL[c]); j+=1
        elif c==0xFD: out.append('{B%02X}'%b[j+1]); j+=2
        elif c==0xFC:
            k=b[j+1]; n={0x04:3,0x0B:2,0x10:2,0x06:1,0x07:0,0x09:0,0x0A:0,0x0C:1,0x08:1,0x11:1,0x12:1,0x13:1,0x14:1,0x01:1,0x02:1,0x03:1,0x05:1,0x0D:0,0x0E:1,0x15:0,0x16:0,0x17:0,0x18:0}.get(k)
            if n is None: return None,j
            out.append('{C'+b[j+1:j+2+n].hex()+'}'); j+=2+n
        else: return None,j
    return None,j
def extract(b,start=0,end=None,minlen=4):
    end=end or len(b); res=[]; i=start
    while i<end:
        s,j=decode(b,i)
        if s is not None and len(s)>=minlen and sum(ch.isalpha() for ch in s)>=minlen*0.6:
            res.append((i,s)); i=j
        else: i=max(j,i+1) if s is None else j
    return res
